check(base_url_absolute() === 'http://localhost:8000', 'Host header cannot poison reset links');
$_SERVER['HTTP_X_FORWARDED_PROTO'] = 'https'; $_SERVER['REMOTE_ADDR']='203.0.113.20';
check(!request_is_https(), 'Untrusted forwarded protocol rejected');
$platform = ['issuer'=>'https://platform.example','client_id'=>'client'];
