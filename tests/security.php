check($again === $prepared, 'Quiz subset stable across reload');
$public = strip_quiz_answers($prepared);
check(!isset($public['modules'][0]['lessons'][0]['quiz']['questions'][0]['options'][0]['correct']), 'Answer key removed');
$graded = quiz_grade(quiz_find('sample', 'quiz-1'), ['q0'=>[0], 'q1'=>[1]], ['q0','q1']);
check($graded['passed'] && $graded['total'] === 2, 'Correct server grading');
check(!quiz_grade(quiz_find('sample','quiz-1'), ['q0'=>[1], 'q1'=>[0]], ['q0','q1'])['passed'], 'Wrong answers fail');
check(safe_media_ref("java\nscript:alert(1)") === '', 'Control-character URI rejected');
check(!str_contains(cr_inline('[x](javascript:alert(1))'), 'href='), 'Markdown script URL rejected');
check(!str_contains(editor_sanitize_html('<img/onerror=alert(1) src="media/x.png">'), 'onerror'), 'Malformed event handler removed');
check(!str_contains(editor_sanitize_html('<a href="jav&#x61;script:alert(1)">x</a>'), 'href='), 'Entity-obfuscated script removed');
check(!str_contains(editor_sanitize_html('<iframe srcdoc="bad" src="https://example.org"></iframe>'), 'iframe'), 'srcdoc iframe removed');
check(!url_is_safe_public('http://127.0.0.1/'), 'Local SSRF rejected');
check(!url_is_safe_public('http://[::1]/'), 'IPv6 local SSRF rejected');
check(!url_is_safe_public('http://[::ffff:127.0.0.1]/'), 'Mapped local IPv6 rejected');
check(!url_is_safe_public('http://169.254.169.254/'), 'Metadata SSRF rejected');
