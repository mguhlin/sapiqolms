check($ltiUser['role'] === 'learner' && (int)$ltiUser['id'] !== $admin, 'LTI cannot impersonate or grant local admin');
check(lti_provision_user(['sub'=>'remote-user'], $platform)['id'] === $ltiUser['id'], 'Stable platform identity');
$other = lti_provision_user(['sub'=>'remote-user'], $platform + ['other'=>'unused']);
check($other['id'] === $ltiUser['id'], 'Irrelevant platform fields do not alter identity');
$jwt = jwt_sign(['sub'=>'test']);
check(jwt_verify($jwt, ['public_key'=>lti_keys()['public']]) === null, 'JWT without lifetime rejected');
