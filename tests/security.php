check($snapshotDb->query('PRAGMA integrity_check')->fetchColumn() === 'ok', 'Backup snapshot integrity');
check((int) $snapshotDb->query('SELECT COUNT(*) FROM users')->fetchColumn() >= 3, 'Snapshot retains users');
