$course = course_by_slug('sample'); $cid = (int) $course['id'];
check(isset(record_progress($uid, $cid, 'invented', true)['error']), 'Forged progress rejected');
check(completed_units($uid, $cid) === 0, 'Forged progress cannot affect completion');
check(isset(record_progress($uid, $cid, 'lesson-2', true)['error']), 'Sequential lock enforced');
check(!isset(record_progress($uid, $cid, 'lesson-1', true)['error']), 'Legitimate lesson completion works');
check(course_access_error($uid, $course) === null, 'Published course accessible');
$draft = $course; $draft['status'] = 'draft';
check(course_access_error($uid, $draft) !== null, 'Draft access rejected');
db_run('UPDATE enrollments SET expires_at=? WHERE user_id=? AND course_id=?', ['2020-01-01 00:00:00', $uid, $cid]);
check(course_access_error($uid, $course) !== null, 'Expired enrollment rejected');
